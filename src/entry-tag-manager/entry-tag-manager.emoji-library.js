/**
 * The three groups the grid draws a heading for, in display order. Frozen all
 * the way down — `Object.freeze` is shallow, so the group objects and their
 * arrays are frozen too, or a caller could edit the shipped list.
 */
export const EMOJI_GROUPS = Object.freeze(
  [
    { label: 'Nature', emoji: NATURE },
    { label: 'Creatures', emoji: CREATURES },
    { label: 'Objects', emoji: OBJECTS },
  ].map((group) => Object.freeze({ label: group.label, emoji: Object.freeze(group.emoji) })),
);

/** Every emoji the grid offers, derived from the groups so the two cannot drift apart. */
export const LIBRARY_EMOJI = Object.freeze(EMOJI_GROUPS.flatMap((group) => group.emoji));

/** U+FE0E (text form) and U+FE0F (colour form): they change how an emoji draws, not which it is. */
const VARIATION_SELECTORS = /[︎️]/gu;

/**
 * Whether two strings are the same emoji, ignoring the colour-variant
 * selector — a tag saved as `⚔` is the grid's `⚔️`.
 * @param {string|null|undefined} a
 * @param {string|null|undefined} b
 */
export function isSameEmoji(a, b) {
  if (typeof a !== 'string' || typeof b !== 'string') return false;
  const key = a.replace(VARIATION_SELECTORS, '');
  return key !== '' && key === b.replace(VARIATION_SELECTORS, '');
}
